def _read_csv(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    if not path.is_file():
        raise FileNotFoundError(f"Required snapshot does not exist: {path}")
    with path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if not reader.fieldnames:
            raise ValueError(f"Snapshot has no header: {path.name}")
        rows = list(reader)
    if not rows:
        raise ValueError(f"Snapshot contains no data rows: {path.name}")
    return list(reader.fieldnames), rows


def load_snapshots() -> dict[str, tuple[list[str], list[dict[str, str]]]]:
    return {
        table: _read_csv(DATA_DIR / filename)
        for table, filename in TABLE_FILES.items()
    }


def _require_unique(
    table: str, rows: list[dict[str, str]], key: str
) -> set[str]:
    values = [row[key].strip() for row in rows]
    if any(not value for value in values):
        raise ValueError(f"{table}[{key}] contains a blank key")
    distinct = set(values)
    if len(distinct) != len(values):
        raise ValueError(f"{table}[{key}] contains duplicate keys")
    return distinct


def validate_snapshots(
    snapshots: dict[str, tuple[list[str], list[dict[str, str]]]],
) -> dict[str, int]:
    expected_tables = set(CSV_TABLES)
    if set(snapshots) != expected_tables:
        raise ValueError("The snapshot inventory must contain exactly six tables")

    columns = {name: set(snapshots[name][0]) for name in CSV_TABLES}
    rows = {name: snapshots[name][1] for name in CSV_TABLES}
    for table in CSV_TABLES:
        if not set(KEY_COLUMNS.get(table, ())) <= columns[table]:
            raise ValueError(f"{table} is missing one or more business keys")

    city_keys = _require_unique("DimCity", rows["DimCity"], "city_id")
    category_keys = _require_unique("DimCategory", rows["DimCategory"], "category_id")
    source_keys = _require_unique("DimSource", rows["DimSource"], "source_id")
    listing_keys = _require_unique("FactListings", rows["FactListings"], "business_id")
    issue_keys = _require_unique(
        "FactQualityIssues", rows["FactQualityIssues"], "issue_id"
    )
    listing_id_values = {
        row["business_id"].strip() for row in rows["FactListings"]
    }
    if not {row["business_id"].strip() for row in rows["FactQualityIssues"]} <= listing_id_values:
        raise ValueError("FactQualityIssues contains business IDs absent from FactListings")

    for table in ("FactListings", "FactCityCategoryCoverage"):
        for row in rows[table]:
            if row["city_id"].strip() not in city_keys:
                raise ValueError(f"{table} contains a city_id absent from DimCity")
            if row["category_id"].strip() not in category_keys:
                raise ValueError(f"{table} contains a category_id absent from DimCategory")
    for row in rows["FactListings"]:
        if row["source_id"].strip() not in source_keys:
            raise ValueError("FactListings contains a source_id absent from DimSource")

    pair_values = [
        (row["city_id"].strip(), row["category_id"].strip())
        for row in rows["FactCityCategoryCoverage"]
    ]
    if len(set(pair_values)) != len(pair_values):
        raise ValueError("FactCityCategoryCoverage contains duplicate city-category pairs")
    expected_pairs = {(city, category) for city in city_keys for category in category_keys}
    if set(pair_values) != expected_pairs:
        raise ValueError("FactCityCategoryCoverage does not cover the full dimension grid")
    if sum(int(row["listing_count"]) for row in rows["FactCityCategoryCoverage"]) != len(
        rows["FactListings"]
    ):
        raise ValueError("City-category listing counts do not reconcile to FactListings")
    if sum(int(row["is_covered"]) for row in rows["FactCityCategoryCoverage"]) != 123:
        raise ValueError("Covered-pair total differs from the offline reference")
    if len(rows["FactListings"]) != 2252 or len(listing_keys) != 2252:
        raise ValueError("FactListings must contain 2,252 distinct business IDs")
    if len(rows["FactQualityIssues"]) != 3762 or len(issue_keys) != 3762:
        raise ValueError("FactQualityIssues must contain 3,762 unique issue IDs")
    if len(rows["FactCityCategoryCoverage"]) != 144:
        raise ValueError("FactCityCategoryCoverage must contain 144 unique pairs")

    return {table: len(rows[table]) for table in CSV_TABLES}


def _m_queries() -> tuple[str, dict[str, tuple[str, dict[str, str]]]]:
    text = POWER_QUERY.read_text(encoding="utf-8")
    markers = list(
        re.finditer(r"(?m)^// ---------- Query name: ([A-Za-z_][A-Za-z0-9_]*) ----------\s*$", text)
    )
    queries: dict[str, tuple[str, dict[str, str]]] = {}
    for index, marker in enumerate(markers):
        end = markers[index + 1].start() if index + 1 < len(markers) else len(text)
        section = text[marker.end() : end]
        start = section.find("let")
        if start < 0:
            raise ValueError(f"Power Query block is missing a let expression: {marker.group(1)}")
        query = section[start:].strip()
        types = {
            column: kind
            for column, kind in re.findall(
                r'\{\s*"([^"]+)"\s*,\s*(Int64\.Type|type number|type text|type date)\s*\}',
                query,
            )
        }
        queries[marker.group(1)] = (query, types)

    missing = set(CSV_TABLES) - set(queries)
    if missing:
        raise ValueError(f"Power Query M is missing table queries: {sorted(missing)}")
    parameter_match = re.search(
        r'(?m)^"([^"\r\n]+)"\s+meta\s+\[IsParameterQuery\s*=\s*true,.*\]\s*$',
        text,
    )
    if not parameter_match:
        raise ValueError("Power Query M is missing the DataFolder parameter expression")
    return parameter_match.group(0), queries


def _column_tmdl(table: str, column: str, data_type: str) -> str:
    lines = [
        f"column {column}",
        f"    dataType: {data_type}",
        f"    lineageTag: {pbip._guid(f'{table}.{column}')}",
    ]
    if column in KEY_COLUMNS.get(table, set()):
        lines.append("    isKey")
    if column in HIDDEN_COLUMNS.get(table, set()):
        lines.append("    isHidden")
    if table == "DimCategory" and column == "category_name":
        lines.append("    sortByColumn: display_order")
    if table == "FactListings" and column == "quality_band":
        lines.append("    sortByColumn: quality_band_sort")
    if table == "FactCityCategoryCoverage" and column == "opportunity_tier":
        lines.append("    sortByColumn: opportunity_tier_sort")
    category = {
        "latitude": "Latitude",
        "longitude": "Longitude",
        "centroid_latitude": "Latitude",
        "centroid_longitude": "Longitude",
        "source_record_url": "WebUrl",
    }.get(column)
    if category:
        lines.append(f"    dataCategory: {category}")
    lines.extend(["    summarizeBy: none", f"    sourceColumn: {column}"])
    return "\n".join(lines)


def _format_and_folder(dax_text: str) -> tuple[dict[str, str | None], dict[str, str]]:
    measures = [name for name, _ in pbip.parse_dax_measures(dax_text)]
    if set(measures) != set(FORMAT_MAP):
        raise ValueError("Measure format map does not match the DAX measure inventory")
    folders = dict(MEASURE_FOLDERS)
    for name in measures:
        if name not in folders:
            if name in {
                "Duplicate Count",
                "Missing Phone Count",
                "Missing Address Count",
                "Missing Phone %",
                "Missing Address %",
                "Invalid Phone Count",
                "Invalid Address Count",
                "Missing Coordinate Count",
                "Invalid Coordinate Count",
                "Outside City Bbox Count",
                "Missing Business Name Count",
                "Missing Category Count",
                "Quality Issue Rows",
                "Data Quality Issue Count",
                "Needs Review Records",
                "Complete Records",
                "Complete Records %",
                "Avg Quality Score",
                "Data Quality %",
            }:
                folders[name] = "03 Data Quality"
            else:
                folders[name] = "04 Opportunity"
    return FORMAT_MAP, folders


def _measure_tmdl(
    name: str, expression: str, format_string: str | None, folder: str
) -> str:
    escaped = name.replace("'", "''")
    lines = [f"measure '{escaped}' =", pbip._indent(expression, 8)]
    if format_string:
        lines.append(f"    formatString: {format_string}")
    lines.extend(
        [
            f"    displayFolder: '{folder}'",
            f"    lineageTag: {pbip._guid(f'measure.{name}')}",
        ]
    )
    return "\n".join(lines)


def _relationships_tmdl() -> str:
    parts = []
    for index, (from_column, to_column, from_cardinality, to_cardinality) in enumerate(
        RELATIONSHIPS
    ):
        parts.append(
            "\n".join(
                [
                    f"relationship {pbip._guid(f'relationship.{index}.{from_column}.{to_column}')}",
                    f"    fromColumn: {from_column}",
                    f"    toColumn: {to_column}",
                    f"    fromCardinality: {from_cardinality}",
                    f"    toCardinality: {to_cardinality}",
                    "    isActive",
                    "    crossFilteringBehavior: oneDirection",
                ]
            )
        )
    return "\n\n".join(parts) + "\n"


def _model_files(
    snapshots: dict[str, tuple[list[str], list[dict[str, str]]]],
) -> dict[str, str]:
    parameter, queries = _m_queries()
    data_folder = str(DATA_DIR.resolve())
    if not data_folder.endswith("\\"):
        data_folder += "\\"
    parameter = f'"{data_folder}" meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = true]'
    model_tables = (*CSV_TABLES, "_Measures")
    model_lines = [
        "/// " + MARKER,
        "model Model",
        "    culture: en-US",
        "    defaultPowerBIDataSourceVersion: powerBI_V3",
        "    sourceQueryCulture: en-US",
        "    dataAccessOptions",
        "        legacyRedirects",
        "        returnErrorValuesAsNull",
        *[f"ref table {table}" for table in model_tables],
        "ref expression DataFolder",
        "ref cultureInfo en-US",
        "",
    ]
    files = {
        "definition.pbism": json.dumps(
            {"$schema": SEMANTIC_MODEL_SCHEMA, "version": "4.0"}, indent=2
        )
        + "\n",
        "definition/database.tmdl": "database\n    compatibilityLevel: 1601\n",
        "definition/model.tmdl": "\n".join(model_lines),
        "definition/relationships.tmdl": _relationships_tmdl(),
        "definition/expressions.tmdl": (
            "/// " + MARKER + "\nexpression DataFolder =\n    " + parameter + "\n"
        ),
    }

    dax_text = MEASURES_DAX.read_text(encoding="utf-8")
    formats, folders = _format_and_folder(dax_text)
    measures = pbip.parse_dax_measures(dax_text)
    for table in CSV_TABLES:
        csv_columns = snapshots[table][0]
        query, type_names = queries[table]
        if set(type_names) != set(csv_columns):
            raise ValueError(
                f"Power Query type declarations do not match {table}.csv: "
                f"missing={sorted(set(csv_columns) - set(type_names))}, "
                f"extra={sorted(set(type_names) - set(csv_columns))}"
            )
        columns = [
            _column_tmdl(table, column, TYPE_MAP[type_names[column]])
            for column in csv_columns
        ]
        if table == "FactCityCategoryCoverage":
            columns.append(
                "\n".join(
                    [
                        "column 'Pair Label' =",
                        "    RELATED ( DimCity[city_name] ) & \" | \" & RELATED ( DimCategory[category_name] )",
                        "    dataType: string",
                        f"    lineageTag: {pbip._guid('FactCityCategoryCoverage.Pair Label')}",
                        "    summarizeBy: none",
                    ]
                )
            )
        body = [
            "/// " + MARKER,
            f"table {table}",
            "",
            pbip._indent("\n\n".join(columns), 4),
            "",
            pbip._indent(
                "\n".join(
                    [
                        f"partition {table} = m",
                        "    mode: import",
                        "    source =",
                        pbip._indent(query, 8),
                    ]
                ),
                4,
            ),
            "",
        ]
        files[f"definition/tables/{table}.tmdl"] = "\n".join(body)

    measure_columns = _column_tmdl("_Measures", "MeasureHost", "int64").replace(
        "    sourceColumn: MeasureHost", "    sourceColumn: MeasureHost"
    )
    measure_body = [
        "/// " + MARKER,
        "table _Measures",
        "",
        pbip._indent(measure_columns, 4),
        "",
        *[
            pbip._indent(_measure_tmdl(name, expression, formats[name], folders[name]), 4)
            for name, expression in measures
        ],
        "",
        pbip._indent(
            "\n".join(
                [
                    "partition _Measures = m",
                    "    mode: import",
                    "    source =",
                    '        #table(type table [MeasureHost = Int64.Type], {{0}})',
                ]
            ),
            4,
        ),
        "",
    ]
    files["definition/tables/_Measures.tmdl"] = "\n".join(measure_body)
    return files


def _column_field(table: str, column: str) -> dict[str, Any]:
    return {
        "Column": {
            "Expression": {"SourceRef": {"Entity": table}},
            "Property": column,
        }
    }


def _measure_field(measure: str) -> dict[str, Any]:
    return {
        "Measure": {
            "Expression": {"SourceRef": {"Entity": "_Measures"}},
            "Property": measure,
        }
    }


def _projection(
    field: dict[str, Any], query_ref: str, display_name: str | None = None
) -> dict[str, Any]:
    result: dict[str, Any] = {"field": field, "queryRef": query_ref}
    if display_name:
        result["displayName"] = display_name
    return result


def _column_projection(
    table: str, column: str, label: str | None = None
) -> dict[str, Any]:
    return _projection(_column_field(table, column), f"{table}.{column}", label)


def _measure_projection(measure: str, label: str | None = None) -> dict[str, Any]:
    return _projection(_measure_field(measure), f"_Measures.{measure}", label)


def _visual(
    name: str,
    visual_type: str,
    title: str,
    position: tuple[int, int, int, int],
    roles: dict[str, list[dict[str, Any]]],
) -> dict[str, Any]:
    x, y, width, height = position
    return {
        "$schema": VISUAL_SCHEMA,
        "name": name,
        "position": {
            "x": x,
            "y": y,
            "z": 0,
            "width": width,
            "height": height,
            "tabOrder": y * PAGE_WIDTH + x,
        },
        "visual": {
            "visualType": visual_type,
            "query": {
                "queryState": {
                    role: {"projections": projections}
                    for role, projections in roles.items()
                }
            },
            "visualContainerObjects": {
                "title": [
                    {
                        "properties": {
                            "show": {"expr": {"Literal": {"Value": "true"}}},
                            "text": {
                                "expr": {
                                    "Literal": {
                                        "Value": "'" + title.replace("'", "''") + "'"
                                    }
                                }
                            },
                        }
                    }
                ]
            },
        },
    }


def _card(name: str, measure: str, title: str, pos: tuple[int, int, int, int]):
    return _visual(
        name, "card", title, pos, {"Data": [_measure_projection(measure, title)]}
    )


def _slicer(
    name: str, table: str, column: str, title: str, pos: tuple[int, int, int, int]
):
    return _visual(
        name, "slicer", title, pos, {"Values": [_column_projection(table, column, title)]}
    )


def _chart(
    name: str,
    visual_type: str,
    title: str,
    pos: tuple[int, int, int, int],
    category_fields: list[tuple[str, str]],
    measures: list[str],
    tooltips: list[tuple[str, str]] | None = None,
    tooltip_measures: list[str] | None = None,
    series_fields: list[tuple[str, str]] | None = None,
):
    roles: dict[str, list[dict[str, Any]]] = {
        "Category": [_column_projection(*field) for field in category_fields],
        "Y": [_measure_projection(measure) for measure in measures],
    }
    if series_fields:
        roles["Series"] = [_column_projection(*field) for field in series_fields]
    tooltip_projections = [
        _column_projection(*field) for field in (tooltips or [])
    ] + [_measure_projection(measure) for measure in (tooltip_measures or [])]
    if tooltip_projections:
        roles["Tooltips"] = tooltip_projections
    return _visual(name, visual_type, title, pos, roles)


