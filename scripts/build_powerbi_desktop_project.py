def _report_files() -> dict[str, str]:
    files: dict[str, str] = {
        "definition.pbir": json.dumps(
            {
                "$schema": REPORT_SCHEMA,
                "version": "4.0",
                "datasetReference": {
                    "byPath": {"path": "../BusinessPulse.SemanticModel"}
                },
            },
            indent=2,
        )
        + "\n",
        "definition/report.json": json.dumps(
            {
                "$schema": REPORT_DEFINITION_SCHEMA,
                "themeCollection": {
                    "baseTheme": {
                        "name": "CY24SU06",
                        "reportVersionAtImport": "5.52",
                        "type": "SharedResources",
                    }
                },
                "reportSource": "Default",
            },
            indent=2,
        )
        + "\n",
        "definition/version.json": json.dumps(
            {"$schema": VERSION_SCHEMA, "version": "1.0.0"}, indent=2
        )
        + "\n",
    }
    pages = _page_visuals()
    order = list(pages)
    files["definition/pages/pages.json"] = json.dumps(
        {
            "$schema": PAGES_SCHEMA,
            "pageOrder": order,
            "activePageName": order[0],
        },
        indent=2,
    ) + "\n"
    for page_name, (display_name, visuals) in pages.items():
        if not visuals:
            raise ValueError(f"Generated page has no visuals: {display_name}")
        folder = f"definition/pages/{page_name}"
        files[f"{folder}/page.json"] = json.dumps(
            {
                "$schema": PAGE_SCHEMA,
                "name": page_name,
                "displayName": display_name,
                "displayOption": "FitToPage",
                "height": PAGE_HEIGHT,
                "width": PAGE_WIDTH,
            },
            indent=2,
        ) + "\n"
        for visual in visuals:
            pos = visual["position"]
            if (
                pos["x"] < 0
                or pos["y"] < 0
                or pos["x"] + pos["width"] > PAGE_WIDTH
                or pos["y"] + pos["height"] > PAGE_HEIGHT
            ):
                raise ValueError(f"Visual exceeds the 16:9 page: {visual['name']}")
            files[f"{folder}/visuals/{visual['name']}/visual.json"] = (
                json.dumps(visual, indent=2) + "\n"
            )
    return files


def generate_project(
    output_dir: Path = OUTPUT_DIR,
) -> dict[str, Any]:
    snapshots = load_snapshots()
    row_counts = validate_snapshots(snapshots)
    dax_text = MEASURES_DAX.read_text(encoding="utf-8")
    model_files = _model_files(snapshots)
    report_files = _report_files()
    root_files = {
        "BusinessPulse.pbip": json.dumps(
            {
                "$schema": PROJECT_SCHEMA,
                "version": "1.0",
                "artifacts": [{"report": {"path": "BusinessPulse.Report"}}],
                "settings": {"enableAutoRecovery": True},
            },
            indent=2,
        )
        + "\n",
        ".generated_by_businesspulse": MARKER + "\n",
        "BusinessPulse_theme.json": THEME_JSON.read_text(encoding="utf-8"),
    }
    if output_dir.exists() and not (output_dir / ".generated_by_businesspulse").is_file():
        raise FileExistsError(f"Refusing to overwrite an unmarked directory: {output_dir}")
    for relative, content in root_files.items():
        target = output_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
    for relative, content in report_files.items():
        target = output_dir / "BusinessPulse.Report" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
    for relative, content in model_files.items():
        target = output_dir / "BusinessPulse.SemanticModel" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")

    result = validate_project(output_dir)
    result.update(
        {
            "project": str(output_dir / "BusinessPulse.pbip"),
            "row_counts": row_counts,
            "measure_count": len(pbip.parse_dax_measures(dax_text)),
        }
    )
    return result


def validate_project(output_dir: Path = OUTPUT_DIR) -> dict[str, Any]:
    snapshots = load_snapshots()
    row_counts = validate_snapshots(snapshots)
    project = output_dir / "BusinessPulse.pbip"
    model_root = output_dir / "BusinessPulse.SemanticModel"
    report_root = output_dir / "BusinessPulse.Report"
    required = [
        project,
        report_root / "definition.pbir",
        report_root / "definition" / "report.json",
        report_root / "definition" / "pages" / "pages.json",
        model_root / "definition.pbism",
        model_root / "definition" / "model.tmdl",
        model_root / "definition" / "relationships.tmdl",
        model_root / "definition" / "expressions.tmdl",
    ]
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise FileNotFoundError("Generated PBIP project is incomplete: " + ", ".join(missing))

    table_columns = {table: set(snapshots[table][0]) for table in CSV_TABLES}
    table_columns["FactCityCategoryCoverage"].add("Pair Label")
    model_tables = model_root / "definition" / "tables"
    expected_tables = {*CSV_TABLES, "_Measures"}
    table_files = {path.stem: path for path in model_tables.glob("*.tmdl")}
    if set(table_files) != expected_tables:
        raise ValueError("Semantic model must contain the six source tables and _Measures")
    measure_text = MEASURES_DAX.read_text(encoding="utf-8")
    measure_pairs = pbip.parse_dax_measures(measure_text)
    measure_names = {name for name, _ in measure_pairs}
    generated_measures = set(
        re.findall(
            r"^    measure '((?:[^']|'')+)' =",
            table_files["_Measures"].read_text(encoding="utf-8"),
            re.MULTILINE,
        )
    )
    generated_measures = {name.replace("''", "'") for name in generated_measures}
    if generated_measures != measure_names:
        raise ValueError("Generated TMDL measure inventory differs from measures.dax")

    for table, column in re.findall(r"\b([A-Za-z][A-Za-z0-9_]*)\[([^\]]+)\]", measure_text):
        if table not in table_columns or column not in table_columns[table]:
            raise ValueError(f"DAX references an undefined column: {table}[{column}]")
    for expression in (expression for _, expression in measure_pairs):
        for name in re.findall(r"(?<![A-Za-z0-9_])\[([^\]]+)\]", expression):
            if name not in measure_names:
                raise ValueError(f"DAX references an undefined measure: [{name}]")

    relationship_text = (model_root / "definition" / "relationships.tmdl").read_text(
        encoding="utf-8"
    )
    if len(re.findall(r"(?m)^relationship ", relationship_text)) != len(RELATIONSHIPS):
        raise ValueError("Generated model must contain exactly six relationships")
    if "crossFilteringBehavior: bothDirections" in relationship_text:
        raise ValueError("Relationships must use single-direction filtering")
    for from_column, to_column, from_cardinality, to_cardinality in RELATIONSHIPS:
        for token in (
            f"fromColumn: {from_column}",
            f"toColumn: {to_column}",
            f"fromCardinality: {from_cardinality}",
            f"toCardinality: {to_cardinality}",
        ):
            if token not in relationship_text:
                raise ValueError(f"Relationship contract is missing {token}")

    pages_meta = json.loads(
        (report_root / "definition" / "pages" / "pages.json").read_text(encoding="utf-8")
    )
    if pages_meta["pageOrder"] != list(PAGE_TITLES):
        raise ValueError("Generated report must contain the four pages in the expected order")
    all_visual_names: set[str] = set()
    per_page: dict[str, int] = {}
    for page_name, display_name in PAGE_TITLES.items():
        page_folder = report_root / "definition" / "pages" / page_name
        page_meta = json.loads((page_folder / "page.json").read_text(encoding="utf-8"))
        if page_meta.get("displayName") != display_name:
            raise ValueError(f"Incorrect report page title: {page_name}")
        visual_files = list((page_folder / "visuals").glob("*/visual.json"))
        if not visual_files:
            raise ValueError(f"Report page contains no visuals: {display_name}")
        per_page[display_name] = len(visual_files)
        for visual_path in visual_files:
            visual = json.loads(visual_path.read_text(encoding="utf-8"))
            name = visual["name"]
            if name in all_visual_names:
                raise ValueError(f"Duplicate visual name: {name}")
            all_visual_names.add(name)
            position = visual.get("position", {})
            if (
                position.get("x", -1) < 0
                or position.get("y", -1) < 0
                or position.get("x", -1) + position.get("width", 0) > PAGE_WIDTH
                or position.get("y", -1) + position.get("height", 0) > PAGE_HEIGHT
            ):
                raise ValueError(f"Visual is outside the page canvas: {name}")
            config = visual.get("visual", {})
            if not config.get("visualType") or not config.get("visualContainerObjects", {}).get("title"):
                raise ValueError(f"Visual type or title missing: {name}")
            query_state = config.get("query", {}).get("queryState", {})
            if not query_state:
                raise ValueError(f"Visual has no field bindings: {name}")
            for state in query_state.values():
                for projection in state.get("projections", []):
                    field = projection["field"]
                    if "Column" in field:
                        table = field["Column"]["Expression"]["SourceRef"]["Entity"]
                        column = field["Column"]["Property"]
                        if table not in table_columns or column not in table_columns[table]:
                            raise ValueError(f"{name} references an undefined field: {table}[{column}]")
                    elif "Measure" in field:
                        table = field["Measure"]["Expression"]["SourceRef"]["Entity"]
                        measure = field["Measure"]["Property"]
                        if table != "_Measures" or measure not in measure_names:
                            raise ValueError(f"{name} references an undefined measure: {table}[{measure}]")
    if not any(
        visual.get("visual", {}).get("query", {}).get("queryState", {}).get("Tooltips")
        for path in (report_root / "definition" / "pages").glob("*/visuals/*/visual.json")
        for visual in [json.loads(path.read_text(encoding="utf-8"))]
    ):
        raise ValueError("Report visuals must include tooltip bindings")

    expressions = (model_root / "definition" / "expressions.tmdl").read_text(encoding="utf-8")
    if "MySQL.Database" in expressions or ".env" in expressions:
        raise ValueError("Offline Power BI model must not contain database connection logic")
    return {
        "tables": len(expected_tables),
        "relationships": len(RELATIONSHIPS),
        "measures": len(measure_names),
        "pages": dict(PAGE_TITLES),
        "visuals": len(all_visual_names),
        "visuals_per_page": per_page,
        "row_counts": row_counts,
        "desktop_validation": "pending",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    parser.add_argument("--validate-only", action="store_true")
    args = parser.parse_args(argv)
    result = validate_project(args.output_dir) if args.validate_only else generate_project(args.output_dir)
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
