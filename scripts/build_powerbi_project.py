def _chart(
    name: str,
    visual_type: str,
    title: str,
    pos: tuple[int, int, int, int],
    categories: list[tuple[str, str]],
    values: list[str],
    category_role: str = "Category",
    value_role: str = "Y",
    tooltips: list[str] | None = None,
) -> dict[str, Any]:
    roles: dict[str, list[dict[str, Any]]] = {
        category_role: [_column_projection(table, column) for table, column in categories],
        value_role: [_measure_projection(value) for value in values],
    }
    if tooltips:
        roles["Tooltips"] = [_measure_projection(tip) for tip in tooltips]
    return _visual(name, visual_type, title, pos, roles)


def _table_visual(
    name: str,
    title: str,
    pos: tuple[int, int, int, int],
    fields: list[tuple[str, str]],
    measures: list[str] | None = None,
) -> dict[str, Any]:
    projections = [_column_projection(table, column) for table, column in fields]
    projections.extend(_measure_projection(measure) for measure in (measures or []))
    return _visual(name, "tableEx", title, pos, {"Values": projections})


