def _measure_format(name: str) -> str | None:
    if name in MEASURE_FORMATS:
        return MEASURE_FORMATS[name]
    if name.endswith("%") or name.endswith("Percentage"):
        return "0.0%"
    if name.endswith("Points"):
        return "0.0"
    if name.endswith("Count") or name.endswith("Listings") or name.endswith("Gaps"):
        return "#,##0"
    if name in {"City Rank", "City Rank (All Cities)", "Category Rank"}:
        return "#,##0"
    return None


def parse_dax_measures(text: str) -> list[tuple[str, str]]:
    start_pattern = re.compile(r"^([A-Za-z][A-Za-z0-9 _()%&.-]*)\s*=\s*$")
    lines = text.splitlines()
    measures: list[tuple[str, str]] = []
    current_name: str | None = None
    expression: list[str] = []
    for line in lines:
        match = start_pattern.match(line)
        if match:
            if current_name is not None:
                body = "\n".join(expression).strip()
                if body:
                    measures.append((current_name, body))
            current_name = match.group(1).strip()
            expression = []
        elif current_name is not None:
            expression.append(line)
    if current_name is not None:
        body = "\n".join(expression).strip()
        if body:
            measures.append((current_name, body))
    names = [name for name, _ in measures]
    if len(names) != len(set(names)):
        raise ValueError("The DAX library contains duplicate measure names")
    if not measures:
        raise ValueError("No DAX measures were found")
    return measures


def _tmdl_column(table: str, column: tuple[str, str, str]) -> str:
    name, data_type, category = column
    lines = [
        f"column {name}",
        f"    dataType: {data_type}",
        f"    lineageTag: {_guid(f'{table}.{name}')}",
    ]
    if category == "key":
        lines.append("    isKey")
    if category in {"city", "state", "country", "latitude", "longitude"}:
        model_category = {
            "city": "City",
            "state": "StateOrProvince",
            "country": "Country",
            "latitude": "Latitude",
            "longitude": "Longitude",
        }[category]
        lines.append(f"    dataCategory: {model_category}")
    if category == "hidden":
        lines.append("    isHidden")
    if table == "DimCategory" and name == "category_name":
        lines.append("    sortByColumn: display_order")
    if data_type in {"int64", "double"}:
        lines.append("    summarizeBy: none")
    elif data_type == "string":
        lines.append("    summarizeBy: none")
    else:
        lines.append("    summarizeBy: none")
    lines.append(f"    sourceColumn: {name}")
    return "\n".join(lines)


def _tmdl_measure(name: str, expression: str) -> str:
    escaped_name = name.replace("'", "''")
    lines = [f"measure '{escaped_name}' ="]
    lines.extend(_indent(expression, 8).splitlines())
    measure_format = _measure_format(name)
    if measure_format:
        lines.append(f"    formatString: {measure_format}")
    lines.append(f"    lineageTag: {_guid(f'measure.{name}')}")
    return "\n".join(lines)


def _tables_tmdl(dax_text: str) -> dict[str, str]:
    measures = parse_dax_measures(dax_text)
    output: dict[str, str] = {}
    for table, columns in MODEL_TABLES.items():
        chunks = [f"/// {MARKER}", f"table {table}"]
        chunks.extend(
            ["", *[_indent(_tmdl_column(table, column), 4) for column in columns]]
        )
        if table == "FactListings":
            chunks.extend(
                [
                    "",
                    *[
                        _indent(_tmdl_measure(name, expression), 4)
                        for name, expression in measures
                    ],
                ]
            )
        chunks.extend(["", _indent(_m_partition(table, _table_query(table)), 4)])
        output[f"definition/tables/{table}.tmdl"] = (
            "\n".join(chunks).rstrip() + "\n"
        )
    return output


