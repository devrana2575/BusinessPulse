@dataclass(frozen=True)
class Snapshot:
    listings: list[dict[str, str]]
    opportunities: list[dict[str, str]]
    listing_csv: bytes
    opportunity_csv: bytes


def _read_csv(path: Path, required: set[str]) -> tuple[list[dict[str, str]], bytes]:
    if not path.is_file():
        raise FileNotFoundError(f"Required snapshot file does not exist: {path}")
    raw = path.read_bytes()
    text = raw.decode("utf-8-sig")
    reader = csv.DictReader(text.splitlines())
    columns = set(reader.fieldnames or ())
    missing = sorted(required - columns)
    if missing:
        raise ValueError(f"{path.name} is missing required columns: {', '.join(missing)}")
    rows = list(reader)
    if not rows:
        raise ValueError(f"{path.name} contains no data rows")
    return rows, text.encode("utf-8")


def load_snapshot(
    listings_path: Path = LISTINGS_CSV,
    opportunities_path: Path = OPPORTUNITIES_CSV,
) -> Snapshot:
    listings, listing_csv = _read_csv(listings_path, LISTING_COLUMNS)
    opportunities, opportunity_csv = _read_csv(opportunities_path, OPPORTUNITY_COLUMNS)
    _validate_snapshot(listings, opportunities)
    return Snapshot(listings, opportunities, listing_csv, opportunity_csv)


def _as_bool(value: str, column: str, row_number: int) -> bool:
    normalized = value.strip().casefold()
    if normalized in {"true", "1"}:
        return True
    if normalized in {"false", "0"}:
        return False
    raise ValueError(f"{column} at data row {row_number} is not a Boolean flag")


def _validate_snapshot(
    listings: list[dict[str, str]], opportunities: list[dict[str, str]]
) -> None:
    business_ids = [row["business_id"].strip() for row in listings]
    if any(not value for value in business_ids):
        raise ValueError("The listings snapshot contains a blank business_id")
    if len(set(business_ids)) != len(business_ids):
        raise ValueError("The listings snapshot contains duplicate business_id values")

    snapshot_dates = {row["collection_date"].strip() for row in listings}
    if len(snapshot_dates) != 1 or not next(iter(snapshot_dates), ""):
        raise ValueError("The report source must contain exactly one collection snapshot date")
    sources = {row.get("source", "").strip() for row in listings}
    if sources != {"OpenStreetMap (Overpass API)"}:
        raise ValueError("The offline report currently requires the OSM snapshot source only")

    cities = {row["city"] for row in listings}
    categories = {row["category"] for row in listings}
    opportunity_cities = {row["city_name"] for row in opportunities}
    opportunity_categories = {row["category_name"] for row in opportunities}
    if not cities.issubset(opportunity_cities):
        raise ValueError("A listing city has no matching opportunity-dimension key")
    if not categories.issubset(opportunity_categories):
        raise ValueError("A listing category has no matching opportunity-dimension key")

    city_keys: dict[str, str] = {}
    category_keys: dict[str, str] = {}
    opportunity_pairs: set[tuple[str, str]] = set()
    for row in opportunities:
        city_key = row["city_id"].strip()
        category_key = row["category_id"].strip()
        city_name = row["city_name"].strip()
        category_name = row["category_name"].strip()
        if not city_key or not category_key or not city_name or not category_name:
            raise ValueError("An opportunity dimension key or label is blank")
        if city_name in city_keys and city_keys[city_name] != city_key:
            raise ValueError(f"City {city_name!r} maps to more than one city_id")
        if category_name in category_keys and category_keys[category_name] != category_key:
            raise ValueError(f"Category {category_name!r} maps to more than one category_id")
        city_keys[city_name] = city_key
        category_keys[category_name] = category_key
        pair = (city_key, category_key)
        if pair in opportunity_pairs:
            raise ValueError(f"Duplicate city/category key pair: {pair}")
        opportunity_pairs.add(pair)

    if len(city_keys) != len({row["city_id"] for row in opportunities}):
        raise ValueError("City dimension keys are not unique")
    if len(category_keys) != len({row["category_id"] for row in opportunities}):
        raise ValueError("Category dimension keys are not unique")

    for index, row in enumerate(listings, start=1):
        for column in QUALITY_FLAG_COLUMNS:
            _as_bool(row[column], column, index)
        expected_complete = (
            _as_bool(row["phone_valid"], "phone_valid", index)
            and _as_bool(row["address_valid"], "address_valid", index)
            and not _as_bool(row["duplicate_flag"], "duplicate_flag", index)
        )
        if _as_bool(row["is_complete"], "is_complete", index) != expected_complete:
            raise ValueError(f"is_complete at data row {index} violates the strict audit rule")
        if _as_bool(row["missing_phone"], "missing_phone", index) != (
            not row["phone"].strip()
        ):
            raise ValueError(f"missing_phone at data row {index} disagrees with phone presence")
        if _as_bool(row["missing_address"], "missing_address", index) != (
            not row["address"].strip()
        ):
            raise ValueError(
                f"missing_address at data row {index} disagrees with address presence"
            )
        score = float(row["quality_score"])
        if not 0 <= score <= 100:
            raise ValueError(f"quality_score at data row {index} is outside 0-100")
        latitude = float(row["latitude"])
        longitude = float(row["longitude"])
        if not -90 <= latitude <= 90 or not -180 <= longitude <= 180:
            raise ValueError(f"Coordinate at data row {index} is outside valid bounds")

    listing_counts: dict[tuple[str, str], int] = {}
    for row in listings:
        pair = (row["city"], row["category"])
        listing_counts[pair] = listing_counts.get(pair, 0) + 1
    for row in opportunities:
        expected = listing_counts.get((row["city_name"], row["category_name"]), 0)
        actual = int(row["listing_count"])
        if actual != expected:
            raise ValueError(
                f"Opportunity count mismatch for {row['city_name']} / "
                f"{row['category_name']}: expected {expected}, found {actual}"
            )
        if int(row["is_covered"]) != int(expected > 0):
            raise ValueError(
                f"Coverage flag mismatch for {row['city_name']} / {row['category_name']}"
            )
        if abs(float(row["score_difference"])) > 0.02:
            raise ValueError(
                f"Opportunity score discrepancy exceeds tolerance for "
                f"{row['city_name']} / {row['category_name']}"
            )

    if len(opportunity_pairs) != len(opportunities):
        raise ValueError("Opportunity row keys are not unique")


def _guid(name: str) -> str:
    return str(uuid5(IDENTITY, f"BusinessPulse:{name}"))


def _compressed_m_expression(csv_bytes: bytes) -> str:
    compressor = zlib.compressobj(level=9, wbits=-15)
    compressed = compressor.compress(csv_bytes) + compressor.flush()
    encoded = base64.b64encode(compressed).decode("ascii")
    chunks = [encoded[index : index + 100] for index in range(0, len(encoded), 100)]
    chunk_lines = ",\n".join(f'            "{chunk}"' for chunk in chunks)
    return (
        "let\n"
        "    Encoded = Text.Combine({\n"
        f"{chunk_lines}\n"
        "    }),\n"
        "    Compressed = Binary.FromText(Encoded, BinaryEncoding.Base64),\n"
        "    Decompressed = Binary.Decompress(Compressed, Compression.Deflate),\n"
        "    Csv = Csv.Document(Decompressed, [Delimiter=\",\", Encoding=65001, "
        "QuoteStyle=QuoteStyle.Csv]),\n"
        "    Headers = Table.PromoteHeaders(Csv, [PromoteAllScalars=true])\n"
        "in\n"
        "    Headers"
    )


def _indent(text: str, spaces: int) -> str:
    prefix = " " * spaces
    return "\n".join(prefix + line if line else "" for line in text.splitlines())


def _expressions_tmdl(snapshot: Snapshot) -> str:
    return (
        "/// "
        + MARKER
        + "\nexpression RawListings =\n"
        + _indent(_compressed_m_expression(snapshot.listing_csv), 4)
        + "\n\nexpression RawOpportunities =\n"
        + _indent(_compressed_m_expression(snapshot.opportunity_csv), 4)
        + "\n"
    )


def _m_partition(name: str, query: str) -> str:
    return (
        f"partition {name} = m\n"
        "    mode: import\n"
        "    source =\n"
        + _indent(query, 8)
        + "\n"
    )


