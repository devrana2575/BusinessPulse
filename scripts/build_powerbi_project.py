def _validate_tmdl_documents(model_root: Path) -> int:
    definition_root = model_root / "definition"
    expected_headers = {
        Path("database.tmdl"): re.compile(r"database"),
        Path("model.tmdl"): re.compile(r"model Model"),
        Path("relationships.tmdl"): re.compile(
            r"relationship [0-9a-fA-F-]{36}"
        ),
        Path("expressions.tmdl"): re.compile(r"expression RawListings ="),
    }
    expected_headers.update(
        {
            Path("tables") / f"{table}.tmdl": re.compile(
                rf"table {re.escape(table)}"
            )
            for table in MODEL_TABLES
        }
    )
    expected_paths = set(expected_headers)
    actual_paths = {
        path.relative_to(definition_root)
        for path in definition_root.rglob("*.tmdl")
    }
    if actual_paths != expected_paths:
        raise ValueError(
            "Generated TMDL document inventory is invalid: "
            f"missing={sorted(map(str, expected_paths - actual_paths))}, "
            f"unexpected={sorted(map(str, actual_paths - expected_paths))}"
        )

    for relative_path, header_pattern in expected_headers.items():
        path = definition_root / relative_path
        raw = path.read_bytes()
        if b"\r" in raw:
            raise ValueError(f"TMDL document must use LF line endings: {relative_path}")
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError as error:
            raise ValueError(f"TMDL document is not UTF-8: {relative_path}") from error

        lines = text.splitlines()
        _validate_tmdl_descriptions(relative_path, lines)
        if relative_path == Path("relationships.tmdl") and any(
            line.startswith("///") for line in lines
        ):
            raise ValueError(
                "TMDL relationship document cannot contain documentation comments "
                "because they become relationship descriptions"
            )
        for index, line in enumerate(lines):
            if not line.startswith("///"):
                continue
            next_index = index + 1
            while next_index < len(lines) and lines[next_index].startswith("///"):
                next_index += 1
            if next_index < len(lines) and not lines[next_index].strip():
                raise ValueError(
                    f"Invalid empty line after TMDL documentation comment in "
                    f"{relative_path} line {next_index + 1}"
                )
        declaration_index = next(
            (
                index
                for index, line in enumerate(lines)
                if line.strip() and not line.startswith("///")
            ),
            None,
        )
        if declaration_index is None:
            raise ValueError(f"TMDL document has no declaration: {relative_path}")
        for index, line in enumerate(lines[:declaration_index]):
            if line.strip() and not line.startswith("///"):
                raise ValueError(
                    f"Invalid TMDL comment syntax in {relative_path} "
                    f"line {index + 1}; use /// documentation comments"
                )
        if lines[declaration_index].startswith("//"):
            raise ValueError(
                f"Invalid TMDL comment syntax in {relative_path} "
                f"line {declaration_index + 1}; use /// documentation comments"
            )
        if not header_pattern.fullmatch(lines[declaration_index].strip()):
            raise ValueError(
                f"Invalid TMDL declaration header in {relative_path}: "
                f"{lines[declaration_index]!r}"
            )

        if relative_path == Path("database.tmdl"):
            root_pattern = re.compile(r"database")
        elif relative_path == Path("model.tmdl"):
            root_pattern = re.compile(
                r"(?:model Model|ref table [A-Za-z_][A-Za-z0-9_]*|"
                r"ref expression [A-Za-z_][A-Za-z0-9_]*|ref cultureInfo [A-Za-z-]+)"
            )
        elif relative_path == Path("relationships.tmdl"):
            root_pattern = re.compile(r"relationship [0-9a-fA-F-]{36}")
        elif relative_path == Path("expressions.tmdl"):
            root_pattern = re.compile(r"expression [A-Za-z_][A-Za-z0-9_]* =")
        else:
            root_pattern = re.compile(
                rf"table {re.escape(relative_path.stem)}"
            )
        root_declarations = []
        for line_number, line in enumerate(lines, start=1):
            if not line.strip() or line.startswith("///"):
                continue
            if re.match(r"^ {0,7}//(?!/)", line):
                raise ValueError(
                    f"Invalid TMDL comment syntax in {relative_path} "
                    f"line {line_number}; use /// documentation comments"
                )
            if line[0].isspace():
                if not line.startswith("    "):
                    raise ValueError(
                        f"Invalid TMDL indentation in {relative_path} line {line_number}"
                    )
                continue
            if not root_pattern.fullmatch(line):
                raise ValueError(
                    f"Invalid TMDL root declaration in {relative_path} "
                    f"line {line_number}: {line!r}"
                )
            root_declarations.append(line)

        if relative_path == Path("database.tmdl"):
            if root_declarations != ["database"]:
                raise ValueError("TMDL database document must contain one database declaration")
        elif relative_path == Path("model.tmdl"):
            expected_model_roots = [
                "model Model",
                *[f"ref table {table}" for table in MODEL_TABLES],
                "ref expression RawListings",
                "ref expression RawOpportunities",
                "ref cultureInfo en-US",
            ]
            if root_declarations != expected_model_roots:
                raise ValueError(
                    "TMDL model document must declare all table, expression, "
                    "and culture references"
                )
        elif relative_path == Path("relationships.tmdl"):
            if len(root_declarations) != 6:
                raise ValueError("TMDL relationships document must declare six relationships")
            for line_number, line in enumerate(lines, start=1):
                if (
                    not line.strip()
                    or line.startswith("///")
                    or not line.startswith(" ")
                ):
                    continue
                if not line.startswith("    ") or line.startswith("        "):
                    raise ValueError(
                        f"Invalid TMDL relationship indentation on line {line_number}"
                    )
                if line[4:] == "isActive":
                    continue
                property_match = re.fullmatch(
                    r"([A-Za-z][A-Za-z0-9]*):\s*.*", line[4:]
                )
                if not property_match or property_match.group(1) not in {
                    "fromColumn",
                    "toColumn",
                    "fromCardinality",
                    "toCardinality",
                    "crossFilteringBehavior",
                }:
                    raise ValueError(
                        "Unsupported TMDL relationship property or flag "
                        f"on line {line_number}: {line.strip()!r}"
                    )
        elif relative_path == Path("expressions.tmdl"):
            if root_declarations != [
                "expression RawListings =",
                "expression RawOpportunities =",
            ]:
                raise ValueError("TMDL expressions document has malformed declarations")
        else:
            table = relative_path.stem
            if root_declarations != [f"table {table}"]:
                raise ValueError(f"TMDL table document has malformed declarations: {table}")
            column_declarations = re.findall(
                r"^    column ([A-Za-z_][A-Za-z0-9_]*)$",
                text,
                re.MULTILINE,
            )
            expected_columns = [column for column, _, _ in MODEL_TABLES[table]]
            if column_declarations != expected_columns:
                raise ValueError(f"Invalid TMDL column declarations in {relative_path}")
            key_columns: list[str] = []
            current_column: str | None = None
            for line in lines:
                column_match = re.fullmatch(
                    r"    column ([A-Za-z_][A-Za-z0-9_]*)", line
                )
                if column_match:
                    current_column = column_match.group(1)
                elif line == "        isKey" and current_column is not None:
                    key_columns.append(current_column)
            expected_key_columns = [
                column for column, _, category in MODEL_TABLES[table]
                if category == "key"
            ]
            if key_columns != expected_key_columns:
                raise ValueError(
                    f"Invalid TMDL key-column declarations in {relative_path}: "
                    f"expected {expected_key_columns}, found {key_columns}"
                )
            partition_declarations = re.findall(
                r"^    partition ([A-Za-z_][A-Za-z0-9_]*) = m$",
                text,
                re.MULTILINE,
            )
            if partition_declarations != [table]:
                raise ValueError(f"Invalid TMDL partition declaration in {relative_path}")

    relationship_text = (definition_root / "relationships.tmdl").read_text(
        encoding="utf-8"
    )
    relationship_count = len(
        re.findall(r"^relationship [0-9a-fA-F-]{36}$", relationship_text, re.MULTILINE)
    )
    if relationship_count != 6:
        raise ValueError(
            f"Expected 6 TMDL relationships, found {relationship_count}"
        )

    expression_text = (definition_root / "expressions.tmdl").read_text(
        encoding="utf-8"
    )
    expression_names = re.findall(
        r"^expression ([A-Za-z_][A-Za-z0-9_]*) =$",
        expression_text,
        re.MULTILINE,
    )
    if expression_names != ["RawListings", "RawOpportunities"]:
        raise ValueError("Generated TMDL expressions have invalid declarations")

    model_text = (definition_root / "model.tmdl").read_text(encoding="utf-8")
    table_references = set(
        re.findall(r"^ref table ([A-Za-z_][A-Za-z0-9_]*)$", model_text, re.MULTILINE)
    )
    table_reference_lines = re.findall(
        r"^ref table ([A-Za-z_][A-Za-z0-9_]*)$", model_text, re.MULTILINE
    )
    if (
        table_references != set(MODEL_TABLES)
        or len(table_reference_lines) != len(MODEL_TABLES)
    ):
        raise ValueError("Generated TMDL model must reference all six table documents")
    expression_references = re.findall(
        r"^ref expression ([A-Za-z_][A-Za-z0-9_]*)$",
        model_text,
        re.MULTILINE,
    )
    if expression_references != ["RawListings", "RawOpportunities"]:
        raise ValueError("Generated TMDL model must reference both snapshot expressions")

    return len(expected_paths)


def _validate_tmdl_descriptions(relative_path: Path, lines: list[str]) -> None:
    for index, line in enumerate(lines):
        match = re.fullmatch(r"( +)description:\s*.*", line)
        if not match:
            continue
        indent = len(match.group(1))

        if relative_path == Path("relationships.tmdl"):
            raise ValueError(
                "Unsupported description property on TMDL "
                f"relationship line {index + 1}"
            )
        if relative_path in {
            Path("database.tmdl"),
            Path("model.tmdl"),
            Path("expressions.tmdl"),
        } and indent == 4:
            continue
        if relative_path.parent == Path("tables"):
            if indent == 4:
                continue
            if indent == 8:
                parent_object = next(
                    (
                        previous.strip()
                        for previous in reversed(lines[:index])
                        if previous.startswith("    ")
                        and not previous.startswith("        ")
                        and previous.strip()
                    ),
                    "",
                )
                if re.fullmatch(
                    r"(?:column|measure|partition) .+", parent_object
                ):
                    continue
        raise ValueError(
            f"Unsupported description property placement in {relative_path} "
            f"line {index + 1}"
        )


def validate_project(output_dir: Path = DEFAULT_OUTPUT_DIR) -> dict[str, Any]:
    snapshot = load_snapshot()
    project_path = output_dir / "BusinessPulse.pbip"
    report_root = output_dir / "BusinessPulse.Report"
    model_root = output_dir / "BusinessPulse.SemanticModel"
    required = (
        project_path,
        report_root / "definition.pbir",
        report_root / "definition" / "report.json",
        report_root / "definition" / "version.json",
        report_root / "definition" / "pages" / "pages.json",
        model_root / "definition.pbism",
        model_root / "definition" / "database.tmdl",
        model_root / "definition" / "model.tmdl",
        model_root / "definition" / "relationships.tmdl",
        model_root / "definition" / "expressions.tmdl",
    )
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise FileNotFoundError("Generated project is incomplete: " + ", ".join(missing))

    legacy_report = report_root / "report.json"
    if legacy_report.exists():
        raise ValueError(
            "PBIR and PBIR-Legacy cannot coexist in one PBIP report; "
            f"unexpected legacy definition: {legacy_report}"
        )

    tmdl_document_count = _validate_tmdl_documents(model_root)
