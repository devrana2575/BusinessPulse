def _is_empty_pbir_legacy_report(path: Path) -> bool:
    try:
        report = json.loads(path.read_text(encoding="utf-8"))
        config = json.loads(report["config"])
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, KeyError, TypeError):
        return False
    return (
        set(report) == {"config", "layoutOptimization", "report", "sections"}
        and report["layoutOptimization"] == 0
        and report["report"] == {}
        and report["sections"] == []
        and isinstance(config, dict)
        and config.get("version") == "5.44"
        and config.get("activeSectionIndex") == 0
        and isinstance(config.get("settings"), dict)
    )


def _is_powerbi_auto_date_table(path: Path) -> bool:
    if not re.fullmatch(
        r"(?:DateTableTemplate|LocalDateTable)_[0-9a-fA-F-]{36}\.tmdl",
        path.name,
    ):
        return False
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    table_name = path.stem
    required_patterns = (
        rf"(?m)^table {re.escape(table_name)}$",
        r"(?m)^\s+dataCategory: PaddedDateTableDates$",
        r"(?m)^\s+column Date(?:\s*=|$)",
        r"(?m)^\s+column Year(?:\s*=|$)",
        r"(?m)^\s+column MonthNo(?:\s*=|$)",
        r"(?m)^\s+column Month(?:\s*=|$)",
        r"(?m)^\s+column QuarterNo(?:\s*=|$)",
        r"(?m)^\s+column Quarter(?:\s*=|$)",
        r"(?m)^\s+column Day(?:\s*=|$)",
        r"(?m)^\s+annotation TemplateId = Year$",
        r"(?m)^\s+hierarchy 'Date Hierarchy'$",
        r"(?m)^\s+annotation TemplateId = DateHierarchy$",
    )
    expected_internal_flag = (
        "isPrivate" if table_name.startswith("DateTableTemplate_")
        else "showAsVariationsOnly"
    )
    return all(re.search(pattern, text) for pattern in required_patterns) and (
        re.search(rf"(?m)^\s+{expected_internal_flag}$", text) is not None
    )


def _remove_obsolete_generated_artifacts(
    output_dir: Path,
    generated_model_text: str,
    generated_model_files: dict[str, str],
) -> None:
    legacy_report_paths = (output_dir / "BusinessPulse.Report" / "report.json",)
    obsolete_legacy_reports: list[Path] = []
    for legacy_report in legacy_report_paths:
        if not legacy_report.is_file():
            continue
        if not _is_empty_pbir_legacy_report(legacy_report):
            raise FileExistsError(
                "Refusing to remove an unrecognized or non-empty "
                f"PBIR-Legacy report: {legacy_report}"
            )
        obsolete_legacy_reports.append(legacy_report)

    tables_dir = (
        output_dir / "BusinessPulse.SemanticModel" / "definition" / "tables"
    )
    definition_root = output_dir / "BusinessPulse.SemanticModel" / "definition"
    expected_paths = {
        Path(relative).relative_to("definition")
        for relative in generated_model_files
        if relative.endswith(".tmdl")
    }
    actual_paths = (
        {path.relative_to(definition_root) for path in definition_root.rglob("*.tmdl")}
        if definition_root.is_dir()
        else set()
    )
    obsolete_auto_date_paths = []
    for relative_path in actual_paths - expected_paths:
        path = definition_root / relative_path
        if (
            relative_path.parent == Path("tables")
            and _is_powerbi_auto_date_table(path)
            and not re.search(
                rf"^ref table {re.escape(path.stem)}$",
                generated_model_text,
                re.MULTILINE,
            )
        ):
            obsolete_auto_date_paths.append(path)
        else:
            raise FileExistsError(
                "Refusing to overwrite an unrecognized TMDL document in the "
                f"generated project: {path}"
            )

    for legacy_report in obsolete_legacy_reports:
        legacy_report.unlink()
    for path in obsolete_auto_date_paths:
        path.unlink()


