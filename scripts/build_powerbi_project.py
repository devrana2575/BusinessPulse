def _quality_query() -> str:
    flags = ",\n        ".join(
        f'{{"{column}", each if Text.Lower(Text.From(_)) = "true" or Text.From(_) = "1" '
        f"then 1 else 0, Int64.Type}}"
        for column in QUALITY_FLAG_COLUMNS
    )
    return f"""let
    Source = RawListings,
    ConvertFlags = Table.TransformColumns(Source, {{
        {flags}
    }}),
    TypedColumns = Table.TransformColumnTypes(ConvertFlags, {{
        {{"business_id", type text}},
        {{"validation_status", type text}},
        {{"quality_score", type number}},
        {{"quality_band", type text}}
    }}, "en-US"),
    SelectedColumns = Table.SelectColumns(TypedColumns, {{
        "business_id", "missing_phone", "missing_address", "duplicate_flag",
        "potential_duplicate_flag", "phone_valid", "address_valid", "is_complete",
        "validation_status", "quality_score", "quality_band"
    }})
in
    SelectedColumns"""


