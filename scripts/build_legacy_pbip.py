#!/usr/bin/env python3
"""Build and validate a PBIR-Legacy report from the offline project snapshot.

This generator compiles the four report pages and visuals directly into a PBIR-Legacy
report.json definition (sections array), ensuring full compatibility with older Power BI
Desktop versions that do not support or have PBIR preview enabled.
"""

import sys
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts import build_powerbi_project as pbip

def generate_legacy_project(output_dir: Path | None = None) -> dict:
    if output_dir is None:
        output_dir = ROOT / "powerbi" / "legacy_pbip"
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Copy SemanticModel from powerbi/generated
    sm_src = ROOT / "powerbi" / "generated" / "BusinessPulse.SemanticModel"
    sm_dst = output_dir / "BusinessPulse.SemanticModel"
    if sm_dst.exists():
        shutil.rmtree(sm_dst)
    shutil.copytree(sm_src, sm_dst)
    
    # Root pbip
    (output_dir / "BusinessPulse.pbip").write_text(json.dumps({
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/pbip/pbipProperties/1.0.0/schema.json",
        "version": "1.0",
        "artifacts": [{"report": {"path": "BusinessPulse.Report"}}],
        "settings": {"enableAutoRecovery": True}
    }, indent=2) + "\n", encoding="utf-8")
    
    (output_dir / ".generated_by_businesspulse").write_text(
        "Generated by scripts/build_legacy_pbip.py; do not edit by hand.\n",
        encoding="utf-8"
    )
    
    rep_dir = output_dir / "BusinessPulse.Report"
    rep_dir.mkdir(parents=True, exist_ok=True)
    
    # definition.pbir (version 1.0)
    (rep_dir / "definition.pbir").write_text(json.dumps({
        "version": "1.0",
        "datasetReference": {
            "byPath": {
                "path": "../BusinessPulse.SemanticModel"
            },
            "byConnection": None
        }
    }, indent=2) + "\n", encoding="utf-8")
    
    # .platform
    (rep_dir / ".platform").write_text(json.dumps({
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {"type": "Report", "displayName": "BusinessPulse"},
        "config": {"version": "2.0", "logicalId": "02ee2ab6-1791-4334-bf6e-20b26650371b"}
    }, indent=2) + "\n", encoding="utf-8")
    
    pages = pbip._page_visuals()
    sections = []
    for idx, (page_name, (display_name, visuals)) in enumerate(pages.items()):
        vc_list = []
        for v in visuals:
            pos = v["position"]
            cfg = {
                "name": v["name"],
                "layouts": [
                    {
                        "id": 0,
                        "position": {
                            "x": pos["x"],
                            "y": pos["y"],
                            "z": pos["z"],
                            "width": pos["width"],
                            "height": pos["height"],
                            "tabOrder": pos["tabOrder"]
                        }
                    }
                ],
                "singleVisual": {
                    "visualType": v["visual"]["visualType"],
                    "projections": v["visual"]["query"]["queryState"],
                    "prototypeQuery": v["visual"]["query"].get("queryState"),
                    "vcObjects": v["visual"].get("visualContainerObjects", {}),
                    "objects": v["visual"].get("objects", {})
                }
            }
            vc_list.append({
                "x": float(pos["x"]),
                "y": float(pos["y"]),
                "z": float(pos["z"]),
                "width": float(pos["width"]),
                "height": float(pos["height"]),
                "config": json.dumps(cfg),
                "filters": "[]"
            })
        sections.append({
            "name": page_name,
            "displayName": display_name,
            "filters": "[]",
            "ordinal": idx,
            "width": 1280.0,
            "height": 720.0,
            "config": "{}",
            "visualContainers": vc_list
        })
    
    report_json_content = {
        "config": json.dumps({
            "version": "5.44",
            "themeCollection": {
                "baseTheme": {
                    "name": "CY24SU06",
                    "reportVersionAtImport": "5.52",
                    "type": "SharedResources"
                }
            },
            "activeSectionIndex": 0,
            "defaultDrillFilterOtherVisuals": True,
            "settings": {}
        }),
        "layoutOptimization": 0,
        "structureVersion": 1.0,
        "sections": sections
    }
    
    (rep_dir / "report.json").write_text(json.dumps(report_json_content, indent=2) + "\n", encoding="utf-8")
    total_visuals = sum(len(s["visualContainers"]) for s in sections)
    print(f"Created legacy project at: {output_dir}")
    print(f"  Sections (pages): {len(sections)}")
    print(f"  Visuals: {total_visuals}")
    return {
        "project": str(output_dir / "BusinessPulse.pbip"),
        "page_count": len(sections),
        "visual_count": total_visuals
    }

if __name__ == "__main__":
    generate_legacy_project()
